// Gate 0.4 step 1: generate two ECDSA (secp256k1) keypairs for the client
// (payer) and server (payee) Hedera testnet accounts, and derive each key's
// EVM address. No Hedera account exists yet at this point — Hedera's
// testnet faucet (https://portal.hedera.com/faucet) auto-creates a "hollow"
// account for any EVM address pasted into it, funded with 100 HBAR. The
// hollow account is completed automatically the first time its key signs as
// fee payer (see resolve-accounts.mjs, run after funding).
//
// Docs: https://docs.hedera.com/hedera/getting-started-evm-developers/hedera-testnet-faucet
import { PrivateKey } from '@hiero-ledger/sdk'
import { writeFileSync, readFileSync, existsSync } from 'node:fs'

function generate(label) {
  const key = PrivateKey.generateECDSA()
  const evmAddress = key.publicKey.toEvmAddress()
  console.log(`${label}:`)
  console.log(`  private key : ${key.toStringRaw()}`)
  console.log(`  EVM address : 0x${evmAddress}`)
  return { key: key.toStringRaw(), evmAddress: `0x${evmAddress}` }
}

const client = generate('Client (payer)')
const server = generate('Server (payee)')

const envPath = new URL('./.env', import.meta.url)
const lines = [
  '# Generated by generate-accounts.mjs — Gate 0.4 (docs/11_DAY0_GATES.md)',
  '# Account IDs are blank until resolve-accounts.mjs runs (after faucet funding).',
  `HEDERA_CLIENT_PRIVATE_KEY=${client.key}`,
  `HEDERA_CLIENT_EVM_ADDRESS=${client.evmAddress}`,
  'HEDERA_CLIENT_ACCOUNT_ID=',
  `HEDERA_SERVER_PRIVATE_KEY=${server.key}`,
  `HEDERA_SERVER_EVM_ADDRESS=${server.evmAddress}`,
  'HEDERA_SERVER_ACCOUNT_ID=',
  '',
].join('\n')

if (existsSync(envPath)) {
  console.log('\n.env already exists here — not overwriting. Delete it first if you want to regenerate.')
} else {
  writeFileSync(envPath, lines)
  console.log(`\nWrote ${envPath.pathname}`)
}

console.log('\nNext: fund both EVM addresses at https://portal.hedera.com/faucet (100 HBAR each, no login),')
console.log('then run `npm run resolve-accounts` to fill in the resulting 0.0.X account IDs.')
