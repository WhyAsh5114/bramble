// Package wgnode wraps wireguard-go's Device with the minimal surface
// brambled needs: create a node, add/remove peers by public key, read the
// current peer set back. Peer admission itself is not implemented here —
// WireGuard's own protocol already refuses a handshake from any public key
// that isn't in the device's peer table (see package admission, which is
// what decides who gets added).
//
// Real OS TUN is the default (Config.Netstack is false unless set) — the
// actual demo and the real Gate 0.2 cross-network run both need a genuine
// OS-visible interface, and defaulting to it means forgetting a flag can't
// silently produce the virtual path instead. netstack (gVisor virtual TUN,
// root-free) is an explicit opt-in, used only by automated tests and CI,
// which set Config.Netstack: true.
package wgnode

